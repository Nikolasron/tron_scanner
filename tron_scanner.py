"""
TRON Active Allowance Scanner
Audits the CURRENT on-chain allowance for a list of TRON owner addresses
and writes only the approvals that are still active right now
(allowance > 0 or unlimited). Also labels each spender as
'contract', 'wallet', or 'unknown'.

Reads addresses from BOTH:
  - manual_addresses.txt      (you edit)
  - discovered_addresses.txt  (auto-generated by discover_owners.py)
"""
import os
import sys
import json
import csv
import time
from datetime import datetime, timezone
from typing import List, Dict, Any

import requests

TRONSCAN_API_BASE = "https://apilist.tronscanapi.com/api"
TRONGRID_BASE     = "https://api.trongrid.io"
API_KEY           = os.environ.get("TRONSCAN_API_KEY", "").strip()
TRONGRID_KEY      = os.environ.get("TRONGRID_API_KEY", "").strip()
PAGE_DELAY        = float(os.environ.get("PAGE_DELAY", "0.15"))
MAX_PAGES         = int(os.environ.get("MAX_PAGES_PER_OWNER", "50"))
MAX_ADDRESSES     = int(os.environ.get("MAX_ADDRESSES", "500"))
OUTPUT_JSON       = "active_approvals.json"
OUTPUT_CSV        = "active_approvals.csv"
ADDRESS_FILES     = ["manual_addresses.txt", "discovered_addresses.txt"]

_spender_cache: Dict[str, str] = {}


def _ts_headers() -> Dict[str, str]:
    h = {"accept": "application/json"}
    if API_KEY:
        h["TRON-PRO-API-KEY"] = API_KEY
    return h


def _tg_headers() -> Dict[str, str]:
    h = {"accept": "application/json"}
    if TRONGRID_KEY:
        h["TRON-PRO-API-KEY"] = TRONGRID_KEY
    return h


def classify_spender(addr: str) -> str:
    """Return 'contract' if addr has bytecode, 'wallet' if EOA, 'unknown' on error."""
    if not addr:
        return "unknown"
    if addr in _spender_cache:
        return _spender_cache[addr]
    try:
        r = requests.get(
            f"{TRONGRID_BASE}/wallet/getcontract",
            params={"value": addr, "visible": "true"},
            headers=_tg_headers(),
            timeout=15,
        )
        data = r.json()
        if r.status_code == 200 and (data.get("bytecode") or data.get("contract_address")):
            kind = "contract"
        elif r.status_code == 200:
            kind = "wallet"
        else:
            kind = "unknown"
    except requests.RequestException:
        kind = "unknown"
    _spender_cache[addr] = kind
    time.sleep(0.05)
    return kind


def load_addresses() -> List[str]:
    seen = set()
    for path in ADDRESS_FILES:
        try:
            with open(path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith("#"):
                        seen.add(line)
        except FileNotFoundError:
            continue
    return sorted(seen)[:MAX_ADDRESSES]


def get_active_approvals_for_owner(owner: str) -> List[Dict[str, Any]]:
    url = f"{TRONSCAN_API_BASE}/account/approve/list"
    params = {"address": owner, "limit": 50, "start": 0, "type": "token"}
    results: List[Dict[str, Any]] = []

    for _ in range(MAX_PAGES):
        resp = requests.get(url, params=params, headers=_ts_headers(), timeout=30)
        resp.raise_for_status()
        page = resp.json().get("data") or []

        for rec in page:
            amount_str = rec.get("amount") or "0"
            unlimited  = bool(rec.get("unlimited", False))
            try:
                amount_int = int(amount_str)
            except (TypeError, ValueError):
                amount_int = 0

            if unlimited or amount_int > 0:
                token_info = rec.get("tokenInfo") or {}
                spender = rec.get("to_address") or rec.get("spenderAddress")
                results.append({
                    "owner":          rec.get("from_address") or rec.get("ownerAddress") or owner,
                    "spender":        spender,
                    "spender_type":   classify_spender(spender),
                    "token_contract": rec.get("contract_address") or rec.get("tokenAddress"),
                    "token_symbol":   token_info.get("tokenAbbr") or rec.get("tokenAbbr"),
                    "token_decimals": token_info.get("tokenDecimal") or rec.get("tokenDecimal"),
                    "allowance_raw":  amount_str,
                    "unlimited":      unlimited,
                })

        if len(page) < params["limit"]:
            break
        params["start"] += params["limit"]
        time.sleep(PAGE_DELAY)

    return results


def write_outputs(rows: List[Dict[str, Any]]) -> None:
    payload = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "total_active":     len(rows),
        "approvals":        rows,
    }
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)

    fields = ["owner", "spender", "spender_type", "token_contract",
              "token_symbol", "token_decimals", "allowance_raw", "unlimited"]
    with open(OUTPUT_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for r in rows:
            writer.writerow({k: r.get(k) for k in fields})


def main() -> None:
    addresses = load_addresses()
    print(f"Auditing {len(addresses)} address(es)...")

    all_active: List[Dict[str, Any]] = []
    for i, addr in enumerate(addresses, 1):
        try:
            active = get_active_approvals_for_owner(addr)
            print(f"[{i}/{len(addresses)}] {addr} -> {len(active)} active")
            for a in active:
                tag = "UNLIMITED" if a["unlimited"] else a["allowance_raw"]
                print(f"      {a['owner']} -> {a['spender']} "
                      f"[{a['token_symbol']}] [{a['spender_type']}] {tag}")
            all_active.extend(active)
        except requests.RequestException as e:
            print(f"[{i}/{len(addresses)}] {addr} -> ERROR {e}", file=sys.stderr)

    write_outputs(all_active)
    print(f"Done. {len(all_active)} active approval(s) written.")


if __name__ == "__main__":
    main()
